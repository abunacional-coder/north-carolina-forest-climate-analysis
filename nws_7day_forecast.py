"""Retrieve short-term NWS forecast periods for three North Carolina forest points.

These are official NWS forecasts, not predictions generated by a model in this project.
Precipitation probability (%) is not an estimate of rainfall accumulation.
"""
from pathlib import Path
import sys
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
import requests

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
FIGURES = ROOT / "figures"
DATA.mkdir(exist_ok=True)
FIGURES.mkdir(exist_ok=True)

FORESTS = {
    "DuPont State Recreational Forest": (35.1903, -82.6025),
    "Clemmons Educational State Forest": (35.6741, -78.4893),
    "Bladen Lakes State Forest": (34.6880, -78.5951),
}
HEADERS = {"User-Agent": "NCForestClimatePortfolio/1.0 (educational research)", "Accept": "application/geo+json"}

def fetch_json(url):
    response = requests.get(url, headers=HEADERS, timeout=35)
    response.raise_for_status()
    return response.json()

rows = []
for forest, (lat, lon) in FORESTS.items():
    try:
        point = fetch_json(f"https://api.weather.gov/points/{lat},{lon}")
        forecast_url = point["properties"]["forecast"]
        result = fetch_json(forecast_url)
        updated = result.get("properties", {}).get("updated", "")
        periods = result.get("properties", {}).get("periods", [])
        for period in periods:
            value = period.get("temperature")
            unit = period.get("temperatureUnit")
            temperature = (value - 32) * 5 / 9 if value is not None and unit == "F" else value if unit == "C" else None
            chance = (period.get("probabilityOfPrecipitation") or {}).get("value")
            rows.append({
                "forest": forest,
                "period": period.get("name"),
                "start_time": period.get("startTime"),
                "end_time": period.get("endTime"),
                "temperature_c": round(temperature, 1) if temperature is not None else None,
                "precipitation_chance_pct": chance,
                "short_forecast": period.get("shortForecast", ""),
                "forecast_last_updated": updated,
                "forecast_url": forecast_url,
            })
        print(f"{forest}: retrieved {len(periods)} forecast periods")
    except (requests.RequestException, ValueError, KeyError) as error:
        print(f"{forest}: could not retrieve forecast: {error}")

if not rows:
    sys.exit("No forecast periods retrieved; check network and API availability")

frame = pd.DataFrame(rows)
frame.to_csv(DATA / "nws_7day_forecast.csv", index=False)

fig, (top, bottom) = plt.subplots(2, 1, figsize=(11, 8), sharex=True)
for forest, group in frame.groupby("forest", sort=False):
    dates = pd.to_datetime(group.start_time, utc=True).dt.tz_convert("America/New_York")
    top.plot(dates, group.temperature_c, marker="o", markersize=3, label=forest)
    bottom.plot(dates, group.precipitation_chance_pct, marker="o", markersize=3, label=forest)

top.set_title("NWS short-term forecast near three North Carolina state forests")
top.set_ylabel("Forecast temperature (°C)")
top.legend(fontsize=8)
bottom.set_ylabel("Chance of precipitation (%)")
bottom.set_xlabel("Forecast period (Eastern time)")
bottom.set_ylim(-2, 102)
for axis in (top, bottom):
    axis.grid(alpha=0.3)
bottom.xaxis.set_major_formatter(mdates.DateFormatter("%b %d"))
fig.autofmt_xdate()
fig.text(0.5, 0.01, "NWS forecast periods typically represent daytime/nighttime; precipitation probability is not rainfall amount.", ha="center", fontsize=9)
fig.tight_layout(rect=(0, 0.035, 1, 1))
out = FIGURES / "04_nws_7day_forecast.png"
fig.savefig(out, dpi=160)
plt.close(fig)
print(f"Saved data/nws_7day_forecast.csv and {out}")
